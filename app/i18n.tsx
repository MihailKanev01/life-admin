export function translate(locale:Locale,key:string):string{
  if(locale==="en")return key;
  return messages[locale]?.[key]??key;
}

type I18nValue={locale:Locale;setLocale:(locale:Locale)=>void;t:(key:string)=>string};
const I18nContext=createContext<I18nValue>({
  locale:"en",
  setLocale:()=>undefined,
  t:(key)=>key
});

export function I18nProvider({children}:{children:ReactNode}){
  const [locale,setLocaleState]=useState<Locale>("en");
  const [loaded,setLoaded]=useState(false);
  useEffect(()=>{
    const saved=window.localStorage.getItem("life-admin-language") as Locale|null;
    if(saved&&Object.prototype.hasOwnProperty.call(languageNames,saved))setLocaleState(saved);
    setLoaded(true);
  },[]);
  useEffect(()=>{
    if(!loaded)return;
    document.documentElement.lang=locale;
    window.localStorage.setItem("life-admin-language",locale);
  },[locale,loaded]);
  const value=useMemo<I18nValue>(()=>({
    locale,
    setLocale:setLocaleState,
    t:(key:string)=>translate(locale,key)
  }),[locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(){return useContext(I18nContext);}

export function LanguageSwitcher({compact=false}:{compact?:boolean}){
  const {locale,setLocale,t}=useI18n();
  return <label className={"language-picker"+(compact?" compact":"")}>
    <span className="language-label">{t("Language")}</span>
    <select className="language-select" aria-label={t("Language")} value={locale} onChange={event=>setLocale(event.target.value as Locale)}>
      {(Object.keys(languageNames) as Locale[]).map(code=><option key={code} value={code}>{languageNames[code]}</option>)}
    </select>
  </label>;
}
